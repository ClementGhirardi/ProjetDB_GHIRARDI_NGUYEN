CREATE SCHEMA LOL_ESPORT;
USE LOL_ESPORT;

CREATE TABLE TOURNOI (
    ID_TOURNOI INT,
    NOM_TOURNOI VARCHAR(50),
    DATE_DEB_TOURNOI DATE,
    DATE_FIN_TOURNOI DATE,
    SAISON_TOURNOI VARCHAR(10),
    REGION_TOURNOI VARCHAR(20),
    DOTATION INT,
    PRIMARY KEY (ID_TOURNOI)
);

CREATE TABLE EQUIPE (
    ID_EQUIPE INT,
    NOM_EQUIPE VARCHAR(30),
    TAG_EQUIPE VARCHAR(5),
    PRIMARY KEY (ID_EQUIPE)
);

CREATE TABLE JOUEUR (
    ID_JOUEUR INT,
    PSEUDO_JOUEUR VARCHAR(16),
    NOM_JOUEUR VARCHAR(30),
    PRENOM_JOUEUR VARCHAR(20),
    DATE_NAISS_JOUEUR DATE,
    NATIONALITE_JOUEUR VARCHAR(25),
    PRIMARY KEY (ID_JOUEUR)
);

CREATE TABLE AFFRONTEMENT (
    ID_AFFRONTEMENT INT,
    DATE_HEURE_AFFRONTEMENT DATETIME,
    FORMAT_AFFRONTEMENT VARCHAR(3),
    PHASE_AFFRONTEMENT VARCHAR(15),
    STATUT_AFFRONTEMENT VARCHAR(10),
    SCORE_EQUIPE1 INT,
    SCORE_EQUIPE2 INT,
    ID_TOURNOI INT,
    PRIMARY KEY (ID_AFFRONTEMENT),
    FOREIGN KEY (ID_TOURNOI) REFERENCES TOURNOI(ID_TOURNOI)
);

CREATE TABLE PARTIE (
    ID_AFFRONTEMENT INT,
    NUM_PARTIE INT,
    DUREE_PARTIE TIME,
    PRIMARY KEY (ID_AFFRONTEMENT, NUM_PARTIE),
    FOREIGN KEY (ID_AFFRONTEMENT) REFERENCES AFFRONTEMENT(ID_AFFRONTEMENT)
);

CREATE TABLE CHAMPION (
    ID_CHAMPION INT,
    NOM_CHAMPION VARCHAR(25),
    PRIMARY KEY (ID_CHAMPION)
);

CREATE TABLE AFFECTER (
    ID_JOUEUR INT,
    ID_EQUIPE INT,
    DATE_DEB_AFFECT DATE,
    DATE_FIN_AFFECT DATE,
    ROLE_JOUEUR VARCHAR(10),
    STATUT_JOUEUR VARCHAR(10),
    PRIMARY KEY (DATE_DEB_AFFECT, ID_EQUIPE, ID_JOUEUR),
    FOREIGN KEY (ID_EQUIPE) REFERENCES EQUIPE(ID_EQUIPE),
    FOREIGN KEY (ID_JOUEUR) REFERENCES JOUEUR(ID_JOUEUR)
);

CREATE TABLE PARTICIPER (
    ID_TOURNOI INT,
    ID_EQUIPE INT,
    PRIMARY KEY (ID_TOURNOI, ID_EQUIPE),
    FOREIGN KEY (ID_TOURNOI) REFERENCES TOURNOI(ID_TOURNOI),
    FOREIGN KEY (ID_EQUIPE) REFERENCES EQUIPE(ID_EQUIPE)
);

CREATE TABLE DISPUTER (
    ID_EQUIPE INT,
    ID_AFFRONTEMENT INT,
    NUM_EQUIPE INT,
    PRIMARY KEY (ID_EQUIPE, ID_AFFRONTEMENT),
    FOREIGN KEY (ID_EQUIPE) REFERENCES EQUIPE(ID_EQUIPE),
    FOREIGN KEY (ID_AFFRONTEMENT) REFERENCES AFFRONTEMENT(ID_AFFRONTEMENT)
);

CREATE TABLE EFFECTUER (
    ID_EQUIPE INT,
    ID_AFFRONTEMENT INT,
    NUM_PARTIE INT,
    ID_CHAMPION INT,
    NATURE_BAN_PICK VARCHAR(4),
    PRIMARY KEY (ID_EQUIPE, ID_AFFRONTEMENT, NUM_PARTIE, ID_CHAMPION),
    FOREIGN KEY (ID_EQUIPE) REFERENCES EQUIPE(ID_EQUIPE),
    FOREIGN KEY (ID_AFFRONTEMENT, NUM_PARTIE) REFERENCES PARTIE(ID_AFFRONTEMENT, NUM_PARTIE),
    FOREIGN KEY (ID_CHAMPION) REFERENCES CHAMPION(ID_CHAMPION)
);

CREATE TABLE JOUER (
    ID_JOUEUR INT,
    ID_AFFRONTEMENT INT,
    NUM_PARTIE INT,
    ID_CHAMPION INT,
    NB_KILLS INT,
    NB_DEATHS INT,
    NB_ASSISTS INT,
    PRIMARY KEY (ID_JOUEUR, ID_AFFRONTEMENT, NUM_PARTIE, ID_CHAMPION),
    FOREIGN KEY (ID_JOUEUR) REFERENCES JOUEUR(ID_JOUEUR),
    FOREIGN KEY (ID_AFFRONTEMENT, NUM_PARTIE) REFERENCES PARTIE(ID_AFFRONTEMENT, NUM_PARTIE),
    FOREIGN KEY (ID_CHAMPION) REFERENCES CHAMPION(ID_CHAMPION)
);